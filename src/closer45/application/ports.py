"""Ports: what the agent needs from the outside world."""
from __future__ import annotations

from typing import Dict, List, Protocol, Tuple

from ..domain.models import EmailStep, Invoice, Supplier


class LedgerPort(Protocol):
    def load(self) -> Tuple[List[Invoice], List[Supplier]]: ...


class MailPort(Protocol):
    def send(self, step: EmailStep) -> None: ...
    def fetch_replies(self) -> List[Dict[str, str]]: ...


class BankPort(Protocol):
    def balance(self) -> int: ...
    def status(self, key: str) -> str: ...
    def pay(self, key: str, payee: str, amount: int, approval_digest: str) -> None: ...


class MemoryPort(Protocol):
    def load(self) -> dict: ...
    def save(self, state: dict) -> None: ...


class LLMPort(Protocol):
    def draft_email(self, step: EmailStep) -> Tuple[str, str]: ...
    def explain(self, summary: dict) -> str: ...


class ApproverPort(Protocol):
    def decide(self, card: "ApprovalCard") -> Dict[str, str]: ...
